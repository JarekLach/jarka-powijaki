#!/usr/bin/env node
// Fetch the real weekend forecast for the three Three Skies places and write it
// into Main.dc.html and Phone.dc.html, between the FORECAST-DATA markers.
//
//   node fetch-forecast.mjs            # this coming Sat + Sun
//   node fetch-forecast.mjs --dry      # print the block, write nothing
//
// Source: Open-Meteo (https://open-meteo.com) — free, no API key, CC-BY 4.0.
// Run it anywhere with plain internet access; the Claude Code remote sandbox
// blocks every weather host, which is why the checked-in data is a placeholder.

import { readFileSync, writeFileSync } from 'node:fs';

const PLACES = [
  { key: 'dtg', name: 'Döttingen', lat: 47.5691, lon: 8.2591,  tz: 'Europe/Zurich', tint: '#C3D3B0' },
  { key: 'deb', name: 'Dębina',    lat: 54.5836, lon: 16.9503, tz: 'Europe/Warsaw', tint: '#AFCBD9' },
  { key: 'waw', name: 'Warszawa',  lat: 52.2297, lon: 21.0122, tz: 'Europe/Warsaw', tint: '#EBC0AC' },
];

const HOURS = [6, 9, 12, 15, 18, 21];

// WMO weather codes -> the four icons the artboards draw.
function icon(code) {
  if (code <= 1) return 'sun';
  if (code <= 3 || code === 45 || code === 48) return 'partly';
  if (code >= 95) return 'storm';
  return 'rain';
}

function blurb(code, hi, wind) {
  const windy = wind >= 25;
  if (code >= 95) return 'Thunderstorms in the forecast. Keep the afternoon flexible.';
  if (code >= 80) return 'Showers coming through. Bright spells in between.';
  if (code >= 51) return windy ? 'Rain and a stiff wind all day.' : 'Rain on and off through the day.';
  if (code === 45 || code === 48) return 'Fog first thing, lifting later.';
  if (code >= 2) return windy ? 'Cloud and sunshine, with a decent breeze.' : 'A mix of cloud and sunshine.';
  if (hi >= 28) return 'Hot and clear from morning to well past sunset.';
  return windy ? 'Clear but breezy — fresher than the numbers suggest.' : 'Clear skies more or less all day.';
}

function short(code, wind) {
  if (code >= 95) return 'Storms';
  if (code >= 51) return 'Showers';
  if (code === 45 || code === 48) return 'Fog, then brighter';
  if (wind >= 25) return 'Bright and windy';
  if (code >= 2) return 'Sun and cloud';
  return 'Clear all day';
}

// The two days of the coming weekend (today included if today is Sat or Sun).
function weekend() {
  const d = new Date();
  const dow = d.getDay();                     // 0 Sun .. 6 Sat
  const toSat = dow === 0 ? -1 : 6 - dow;
  const sat = new Date(d); sat.setDate(d.getDate() + toSat);
  const sun = new Date(sat); sun.setDate(sat.getDate() + 1);
  const iso = (x) => x.toISOString().slice(0, 10);
  return [iso(sat), iso(sun)];
}

async function place(p, days) {
  const u = new URL('https://api.open-meteo.com/v1/forecast');
  u.search = new URLSearchParams({
    latitude: p.lat, longitude: p.lon, timezone: p.tz,
    start_date: days[0], end_date: days[1],
    daily: 'weather_code,temperature_2m_max,temperature_2m_min,precipitation_probability_max,wind_speed_10m_max',
    hourly: 'temperature_2m,relative_humidity_2m',
  });
  const r = await fetch(u);
  if (!r.ok) throw new Error(`${p.name}: HTTP ${r.status} ${await r.text()}`);
  const j = await r.json();

  return {
    tint: p.tint,
    days: days.map((date, i) => {
      const code = j.daily.weather_code[i];
      const hi = Math.round(j.daily.temperature_2m_max[i]);
      const lo = Math.round(j.daily.temperature_2m_min[i]);
      const wind = Math.round(j.daily.wind_speed_10m_max[i]);
      const at = (h) => j.hourly.time.indexOf(`${date}T${String(h).padStart(2, '0')}:00`);
      const hum = j.hourly.relative_humidity_2m[at(12)];
      return {
        hi, lo, icon: icon(code),
        blurb: blurb(code, hi, wind),
        short: short(code, wind),
        rain: `${j.daily.precipitation_probability_max[i] ?? 0}%`,
        wind: `${wind} km/h`,
        hum: `${Math.round(hum)}%`,
        hours: HOURS.map((h) => [String(h).padStart(2, '0'),
                                 Math.round(j.hourly.temperature_2m[at(h)])]),
      };
    }),
  };
}

const days = weekend();
const data = {};
for (const p of PLACES) data[p.key] = await place(p, days);

const stamp = new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC';
const block = [
  '/* FORECAST-DATA-START — regenerated by fetch-forecast.mjs; do not hand-edit below */',
  `var META = { source: "Open-Meteo", fetchedAt: ${JSON.stringify(stamp)} };`,
  '',
  'var FORECAST = ' + JSON.stringify(data, null, 2) + ';',
  '/* FORECAST-DATA-END */',
].join('\n');

if (process.argv.includes('--dry')) {
  console.log(`weekend: ${days[0]} .. ${days[1]}\n`);
  console.log(block);
  process.exit(0);
}

const RE = /\/\* FORECAST-DATA-START[\s\S]*?\/\* FORECAST-DATA-END \*\//;
for (const f of ['Main.dc.html', 'Phone.dc.html']) {
  const src = readFileSync(f, 'utf8');
  if (!RE.test(src)) throw new Error(`${f}: FORECAST-DATA markers not found`);
  writeFileSync(f, src.replace(RE, () => block));
  console.log(`updated ${f}`);
}
console.log(`\nweekend ${days[0]} .. ${days[1]} — now re-seed the canvas and republish.`);
